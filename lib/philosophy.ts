/**
 * 3D ヒーローの幕ごとに 1 行ずつ出す「山蔵の考え方」。
 * 文章はサイト内（代表挨拶・経営理念・私たちについて・ヒーローの説明文）から取って短く整えたもの。
 *
 * from / to は**スクロールの生の進み具合（0..1）**で、3D の建て方（hero3d/constants.ts の TIMING,
 * CLAD_END ≒ 0.772, IGNITE.fireStart = 0.776）と同じ物差し。幕が変わるところで行も替わる。
 * 区間どうしの間には少し隙間を置き、前の行が消えきってから次が入るようにしてある。
 *
 * `|` は折り返してよい位置。`|` の間はひと塊として、行の途中で割らない
 * （ブラウザの文節判定に任せると「適正な／価格で」のように割れることがあった）。
 *
 * three.js に依存しないのでページ側からも読める。scripts/build-mincho.py はここから明朝の字を拾う
 * （hero3d/ の中は拾わない）ので、文章を変えたらそれを実行し直すこと。
 */
export const PHILOSOPHY = {
  /** 区間のうち、入り・出にそれぞれ使う割合 */
  fade: 0.25,
  lines: [
    // 引き〜石垣を積む
    { text: "宮大工で修業を積み、|一級建築士へ。", from: 0.22, to: 0.3 },
    // 石垣・礎石
    { text: "日本古来の木組み、|継手、仕口を|得意としています。", from: 0.305, to: 0.37 },
    // 心柱架構が一気に立つ
    { text: "現場も、設計も、|知り尽くした職人が。", from: 0.375, to: 0.45 },
    // 母屋が寄りかかる
    { text: "宮大工の伝統技術を、|現代の住まいに。", from: 0.455, to: 0.545 },
    // 入母屋大屋根
    { text: "地域に根付いた|会社だからこそ、|きめ細やかに、|適正な価格で。", from: 0.55, to: 0.645 },
    // 八角・四角が載り、塗り上がる
    { text: "お客様に|喜んでもらうのが、|一番の喜びです。", from: 0.65, to: 0.765 },
    // 篝火が灯り、障子に明かりが入る
    { text: "百年後も美しい|家づくりを。", from: 0.8, to: 1 },
  ],
} as const

/** 行の番号（壱・弐・参…） */
export const KANJI_NUMERALS = ["壱", "弐", "参", "肆", "伍", "陸", "漆", "捌", "玖", "拾"] as const

const clamp01 = (v: number) => (v < 0 ? 0 : v > 1 ? 1 : v)

/**
 * 進み具合 p での各行の状態 t。
 * -1 = まだ出ていない、-1→0 = 入ってくる途中、0 = 表示中、0→1 = 消えていく途中、1 = 消えた
 */
export function lineState(p: number, from: number, to: number): number {
  const f = (to - from) * PHILOSOPHY.fade
  if (p <= from + f) return clamp01((p - from) / f) - 1
  // 最後の行は、ピンが外れて次の場面が上がってくるまで出したままにする
  if (to >= 1) return 0
  if (p >= to - f) return clamp01((p - (to - f)) / f)
  return 0
}

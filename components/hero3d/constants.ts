//   天主の灯・篝火 … 完成の瞬間にともる。暖色はここにだけ集める
// 寒色と暖色がぶつかる境目に、見る人の目が行く。

/**
 * 方位・仰角から位置を出す。方位の取り方はカメラ（cameraPath.ts）と同じで、
 * 0° が +Z、90° が +X。**カメラと同じ物差しで書く**ことで、
 * 「最後の構図のどこに月が入るか」をそのまま逆算できる。
 */
function fromAzEl(azDeg: number, elDeg: number, r: number): [number, number, number] {
  const a = (azDeg * Math.PI) / 180
  const e = (elDeg * Math.PI) / 180
  return [Math.sin(a) * Math.cos(e) * r, Math.sin(e) * r, Math.cos(a) * Math.cos(e) * r]
}

